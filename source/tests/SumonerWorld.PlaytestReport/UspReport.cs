using System.Globalization;
using System.Text;

namespace SumonerWorld.PlaytestReport;

/// <summary>The B7 outcome for the noticed share.</summary>
public enum UspVerdict
{
    /// <summary>≥ 70%: USP readable, GO on this criterion.</summary>
    Readable,

    /// <summary>55–69%: fix staging and animation, retest with ≥ 10 new testers.</summary>
    PartlyReadable,

    /// <summary>&lt; 55%: gate finding, RE-SCOPE discussion on how memory is shown.</summary>
    NotReadable,
}

/// <summary>
/// Builds the numbers section of <c>qa/playtesting/M1_usp_report.md</c> (QA plan B7) from the telemetry files, the raters' coding
/// sheet and the questionnaire answers. The written findings (top confusion points, quotes) stay with the Data Scientist.
/// </summary>
public static class UspReport
{
    /// <summary>The gate run needs at least this many testers (QA plan B3).</summary>
    public const int GateSize = 20;

    /// <summary>The raters must agree at least this well, or the coding guide is fixed and sessions re-coded (QA plan B5).</summary>
    public const double KappaThreshold = 0.7;

    /// <summary>The B7 decision rule.</summary>
    public static UspVerdict Decide(int noticed, int testers)
    {
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(testers);
        double share = (double)noticed / testers;
        return share >= 0.70 ? UspVerdict.Readable : share >= 0.55 ? UspVerdict.PartlyReadable : UspVerdict.NotReadable;
    }

    /// <summary>Writes the report as Markdown.</summary>
    public static string Build(IReadOnlyList<SessionLog> logs, IReadOnlyList<RaterCode> codes, IReadOnlyList<Responses> responses)
    {
        ArgumentNullException.ThrowIfNull(logs);
        ArgumentNullException.ThrowIfNull(codes);
        ArgumentNullException.ThrowIfNull(responses);
        IReadOnlyList<FinalCode> finals = Coding.Settle(codes);
        FinalCode[] resolved = [.. finals.Where(code => !code.Unresolved)];
        int noticed = resolved.Count(code => code.Noticed);
        double? kappa = Coding.Kappa(codes);
        var text = new StringBuilder();
        void Line(FormattableString line) => text.AppendLine(line.ToString(CultureInfo.InvariantCulture));

        Line($"## Result (generated by SumonerWorld.PlaytestReport)");
        Line($"");
        if (resolved.Length < GateSize)
        {
            Line($"**Coded sessions: {resolved.Length}, below the gate size of {GateSize}. This is not a gate result (pilot or partial run).**");
            Line($"");
        }

        if (resolved.Length > 0)
        {
            (double low, double high) = PlaytestStats.Wilson(noticed, resolved.Length);
            UspVerdict verdict = Decide(noticed, resolved.Length);
            Line($"| Measure | Value |");
            Line($"|---|---|");
            Line($"| Noticed creature memory within 10:00 | **{noticed} of {resolved.Length} ({Percent(noticed, resolved.Length)})**, 95% Wilson interval {low * 100:0}–{high * 100:0}% |");
            Line($"| B7 outcome | {Describe(verdict)}{(resolved.Length < GateSize ? " (indicative only: below the gate size)" : string.Empty)} |");
            Line($"| Median time-to-notice (noticed testers) | {Clock(PlaytestStats.Median(resolved.Where(c => c.TimeToNotice is not null).Select(c => c.TimeToNotice!.Value)))} |");
        }
        else
        {
            Line($"No coded sessions yet.");
        }

        Line($"");
        Line($"### Rater agreement (B5)");
        Line($"- Cohen's κ (A vs B): {(kappa is null ? "n/a" : kappa.Value.ToString("0.00", CultureInfo.InvariantCulture))}, {(kappa >= KappaThreshold ? "meets" : "**below**")} the {KappaThreshold:0.0} threshold{(kappa >= KappaThreshold ? "." : ": fix the coding guide and re-code.")}");
        Line($"- Disagreements settled by rater C: {finals.Count(c => c.Disagreed && !c.Unresolved)}. Unresolved (missing a rater): {finals.Count(c => c.Unresolved)}{Sessions(finals.Where(c => c.Unresolved).Select(c => c.Session))}.");

        Line($"");
        Line($"### Staging (B6 telemetry)");
        MemoryMoment[] window = [.. logs.SelectMany(log => log.Moments).Where(m => m.Time <= SessionLog.WindowSeconds)];
        Line($"- Memory moments in the first 10:00: {window.Length}, of which on screen {window.Count(m => m.InView)} ({Percent(window.Count(m => m.InView), window.Length)}); rumour-driven {window.Count(m => m.Rumour)}.");
        string[] unstaged = [.. logs.Where(log => log.FirstInView is null).Select(log => Short(log.Session))];
        Line($"- Sessions with no memory moment on screen by 10:00 (a staging problem, not readability): {unstaged.Length}{Sessions(unstaged)}.");
        Line($"- Median first on-screen memory moment: {Clock(PlaytestStats.Median(logs.Select(log => log.FirstInView?.Time).OfType<double>()))}.");
        string[] actions = [.. logs.SelectMany(log => log.Actions).GroupBy(a => a.Key, StringComparer.Ordinal).OrderBy(g => g.Key, StringComparer.Ordinal).Select(g => FormattableString.Invariant($"{g.Key} {g.Sum(a => a.Value)}"))];
        Line($"- Player actions, all sessions: {(actions.Length == 0 ? "none" : string.Join(", ", actions))}.");

        Line($"");
        Line($"### Checks");
        var matched = finals.Select(code => (Code: code, Log: logs.FirstOrDefault(log => Matches(log.Session, code.Session)))).ToList();
        string[] noLog = [.. matched.Where(m => m.Log is null).Select(m => m.Code.Session)];
        string[] noticedUnstaged = [.. matched.Where(m => m.Code.Noticed && m.Log is not null && m.Log.FirstInView is null).Select(m => m.Code.Session)];
        string[] late = [.. finals.Where(c => c.Noticed && c.TimeToNotice > SessionLog.WindowSeconds).Select(c => c.Session)];
        Line($"- Coded sessions without a telemetry file: {noLog.Length}{Sessions(noLog)}.");
        Line($"- Coded as noticed although telemetry shows no on-screen memory moment by 10:00 (re-check the video): {noticedUnstaged.Length}{Sessions(noticedUnstaged)}.");
        Line($"- Coded as noticed with a time after 10:00 (does not count under B5, re-check): {late.Length}{Sessions(late)}.");

        Line($"");
        Line($"### Questionnaire (secondary)");
        Line($"- Q2 \"treated you differently\": yes {responses.Count(r => r.TreatedDifferently == true)}, no {responses.Count(r => r.TreatedDifferently == false)}.");
        Line($"- Q3 care (1–7): median {Scale(responses.Select(r => r.Care))}. Q4 keep playing (1–7): median {Scale(responses.Select(r => r.KeepPlaying))}.");
        return text.ToString();
    }

    /// <summary>Whether a telemetry session id and a coding-sheet id name the same session (the sheet may use the 6-character file prefix).</summary>
    public static bool Matches(string telemetrySession, string codedSession)
    {
        ArgumentNullException.ThrowIfNull(telemetrySession);
        ArgumentNullException.ThrowIfNull(codedSession);
        return codedSession.Length >= 6 && telemetrySession.StartsWith(codedSession, StringComparison.OrdinalIgnoreCase);
    }

    private static string Describe(UspVerdict verdict) => verdict switch
    {
        UspVerdict.Readable => "**≥ 70%: USP readable, GO on this criterion**",
        UspVerdict.PartlyReadable => "**55–69%: partly readable.** Fix staging/animation from the findings, retest with ≥ 10 new testers before the gate",
        _ => "**< 55%: not readable.** Gate finding: RE-SCOPE discussion on how memory is shown",
    };

    private static string Percent(int part, int whole) => whole == 0 ? "n/a" : FormattableString.Invariant($"{100.0 * part / whole:0}%");

    private static string Clock(double? seconds) => seconds is null
        ? "n/a"
        : FormattableString.Invariant($"{(int)seconds.Value / 60}:{(int)seconds.Value % 60:00}");

    private static string Scale(IEnumerable<int?> answers)
    {
        double? median = PlaytestStats.Median(answers.OfType<int>().Select(value => (double)value));
        return median is null ? "n/a" : median.Value.ToString("0.#", CultureInfo.InvariantCulture);
    }

    private static string Short(string session) => session.Length > 6 ? session[..6] : session;

    private static string Sessions(IEnumerable<string> sessions)
    {
        string list = string.Join(", ", sessions);
        return list.Length == 0 ? string.Empty : $" ({list})";
    }
}
